# 🏫 중1 통계 3차시 학습지 시안 정답 독립 검산 (2026-11-25 · 📚 차시팩 #1) · gen_ws3.py 를 읽지 않고 자료만 다시 적어 계산
from fractions import Fraction as F
r2 = lambda x: float(round(F(x) * 100) / 100) if False else round(float(x) + 1e-12, 2)
C = {}
# 생각 열기 · STEP 1 (교과서 [표 5] · [표 6])
read = [1, 3, 9, 5, 2]
C['생각 열기 10~15 = 15 %'] = F(read[1], sum(read)) * 100 == 15
C['STEP1 표 6 = 0.05 0.15 0.45 0.25 0.1'] = [F(n, 20) for n in read] == [F(5, 100), F(15, 100), F(45, 100), F(25, 100), F(1, 10)]
C['상대도수 합 = 1'] = sum(F(n, 20) for n in read) == 1
# 문제 1 습도 30곳
hum = [10, 6, 4, 2, 6, 2]
C['문제1 표 (반올림 둘째 자리)'] = [r2(n / 30) for n in hum] == [0.33, 0.2, 0.13, 0.07, 0.2, 0.07]
C['문제1 ⑵ 40~70 % = 40 %'] = F(6 + 4 + 2, 30) * 100 == 40
# 문제 2 호박 25개 (교과서 원자료를 따로 다시 적음)
pump = '270 324 210 315 232 436 271 262 326 425 293 524 269 156 381 227 342 432 286 258 161 284 455 356 409'.split()
pump = [int(x) for x in pump]
cnt = [sum(1 for w in pump if lo <= w < lo + 100) for lo in (100, 200, 300, 400, 500)]
C['문제2 개수 2 11 6 5 1'] = len(pump) == 25 and cnt == [2, 11, 6, 5, 1]
C['문제2 상대도수 0.08 0.44 0.24 0.2 0.04'] = [F(c, 25) for c in cnt] == [F(8, 100), F(44, 100), F(24, 100), F(2, 10), F(4, 100)]
# STEP 5 수영 · 볼링
C['STEP5 14/50 = 0.28 · 12/40 = 0.3 · 볼링이 높음'] = F(14, 50) == F(28, 100) and F(12, 40) == F(3, 10) and F(12, 40) > F(14, 50)
# 문제 3 봉사 (교과서 그래프 눈금 · 답지 48 · 44 와 대조)
A = [F(10, 100), F(16, 100), F(42, 100), F(20, 100), F(12, 100)]
Bv = [F(16, 100), F(24, 100), F(38, 100), F(12, 100), F(10, 100)]
C['문제3 그래프 합 = 1'] = sum(A) == 1 and sum(Bv) == 1
C['문제3 ⑴ A 48 · B 44 (교과서 답지)'] = (A[3] + A[4]) * 150 == 48 and (Bv[3] + Bv[4]) * 200 == 44
C['문제3 ⑵ 6시간 이상 A > B → 있다'] = sum(A[2:]) > sum(Bv[2:])
# 형성평가
cl = [3, 7, 8, 5, 2]
C['형1 10~20 = 0.28'] = F(cl[1], 25) == F(28, 100)
C['형2 20분 이상 = 60 %'] = F(sum(cl[2:]), 25) * 100 == 60 and sum(cl) == 25
C['형4 40 × 0.2 = 8'] = 40 * F(2, 10) == 8
C['형6 1반 9/30 < 2반 8/25'] = F(9, 30) < F(8, 25)
bad = [k for k, ok in C.items() if not ok]
for k, ok in C.items(): print('✔' if ok else '✘', k)
assert not bad, bad
